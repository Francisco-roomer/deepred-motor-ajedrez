def evaluar_tablero(board: chess.Board) -> int:
    if board.is_checkmate():
        return -99999 if board.turn == chess.WHITE else 99999
    if board.is_stalemate() or board.is_insufficient_material():
        return 0

    puntuacion = 0
    for casilla in chess.SQUARES:
        pieza = board.piece_at(casilla)
        if pieza is not None:
            valor_material = VALORES_PIEZAS[pieza.piece_type]
            tabla = TABLAS_PST[pieza.piece_type]

            if pieza.color == chess.WHITE:
                valor_posicional = tabla[chess.square_mirror(casilla)]
                puntuacion += (valor_material + valor_posicional)
            else:
                valor_posicional = tabla[casilla]
                puntuacion -= (valor_material + valor_posicional)

    return puntuacion